import { sqliteTable, text, integer, real } from "drizzle-orm/sqlite-core";

export const users = sqliteTable("users", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  // Stored encrypted at rest via EncryptionService when DB_ENCRYPTION_KEY is set.
  notes: text("notes"),
  createdAt: integer("created_at", { mode: "timestamp" })
    .notNull()
    .$defaultFn(() => new Date()),
});

export const listings = sqliteTable("listings", {
  id: text("id").primaryKey(),
  source: text("source").notNull(),
  externalId: text("external_id"),
  sourceUrl: text("source_url").notNull(),
  offer: text("offer").notNull(),
  title: text("title").notNull(),
  city: text("city").notNull().default(""),
  district: text("district"),
  postalCode: text("postal_code"),
  state: text("state"),
  street: text("street"),
  latitude: real("latitude"),
  longitude: real("longitude"),
  locationPrecision: text("location_precision"),
  brwStatus: text("brw_status"),
  brwZone: text("brw_zone"),
  brwEurPerM2: real("brw_eur_per_m2"),
  brwStichtag: text("brw_stichtag"),
  propertyType: text("property_type").notNull(),
  livingAreaM2: real("living_area_m2"),
  plotAreaM2: real("plot_area_m2"),
  rooms: real("rooms"),
  yearBuilt: integer("year_built"),
  yearRefurbished: integer("year_refurbished"),
  energyClass: text("energy_class"),
  energyKwh: real("energy_kwh"),
  energyCert: text("energy_cert"),
  heating: text("heating"),
  condoFeeEur: real("condo_fee_eur"),
  coldRentEur: real("cold_rent_eur"),
  warmRentEur: real("warm_rent_eur"),
  depositEur: real("deposit_eur"),
  rentContract: text("rent_contract"),
  commissionPercent: real("commission_percent"),
  commissionText: text("commission_text"),
  condition: text("condition"),
  floor: text("floor"),
  featuresJson: text("features_json").notNull().default("[]"),
  snippet: text("snippet").notNull().default(""),
  leasehold: integer("leasehold", { mode: "boolean" }).notNull().default(false),
  groundRentEur: real("ground_rent_eur"),
  monument: integer("monument", { mode: "boolean" }).notNull().default(false),
  tenantOccupied: integer("tenant_occupied", { mode: "boolean" }).notNull().default(false),
  heatingSystem: text("heating_system"),
  energySource: text("energy_source"),
  parkingSpaces: integer("parking_spaces"),
  parkingType: text("parking_type"),
  parkingPriceEur: real("parking_price_eur"),
  bathrooms: integer("bathrooms"),
  bedrooms: integer("bedrooms"),
  availableFrom: text("available_from"),
  listedAt: text("listed_at"),
  portalPreviousPriceEur: real("portal_previous_price_eur"),
  portalMarketEurPerM2: real("portal_market_eur_per_m2"),
  portalMarketLowEurPerM2: real("portal_market_low_eur_per_m2"),
  portalMarketHighEurPerM2: real("portal_market_high_eur_per_m2"),
  descriptionJson: text("description_json"),
  detailsJson: text("details_json"),
  notes: text("notes").notNull().default(""),
  status: text("status").notNull().default("open"),
  createdAt: text("created_at").notNull(),
  updatedAt: text("updated_at").notNull(),
});

export const settings = sqliteTable("settings", {
  key: text("key").primaryKey(),
  value: text("value").notNull(),
});

export const observations = sqliteTable("observations", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  listingId: text("listing_id")
    .notNull()
    .references(() => listings.id),
  seenAt: text("seen_at").notNull(),
  priceEur: real("price_eur"),
  coldRentEur: real("cold_rent_eur"),
  warmRentEur: real("warm_rent_eur"),
  condoFeeEur: real("condo_fee_eur"),
  rawJson: text("raw_json").notNull(),
});
